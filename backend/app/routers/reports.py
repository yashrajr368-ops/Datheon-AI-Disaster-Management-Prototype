import uuid
from datetime import datetime
from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session
from app.database import get_db
from app.models import Location, Shelter
from app.ml_risk_engine import risk_engine
from app.schemas import RiskAnalysisRequest

router = APIRouter(prefix="/api/reports", tags=["Reports"])

@router.post("/generate")
def generate_disaster_report(req: RiskAnalysisRequest, db: Session = Depends(get_db)):
    report_id = f"DATHEON-REP-{uuid.uuid4().hex[:8].upper()}"
    timestamp = datetime.utcnow().isoformat() + "Z"
    
    # Calculate risk evaluation
    eval_res = risk_engine.evaluate_risk(
        rainfall_mm=req.rainfall_mm,
        river_level_m=req.river_level_m,
        historical_flood_events=req.historical_flood_events,
        terrain_susceptibility=req.terrain_susceptibility,
        population_vulnerability=req.population_vulnerability,
        location_name=req.location_name or "Assessed Region"
    )

    # Nearby shelters
    shelters = db.query(Shelter).limit(4).all()
    shelter_data = [
        {
            "name": s.name,
            "district": s.district,
            "capacity": s.capacity,
            "current_occupancy": s.current_occupancy,
            "available_capacity": max(0, s.capacity - s.current_occupancy),
            "status": s.status,
            "accessibility": s.accessibility_info,
            "facilities": s.facilities,
            "contact_phone": s.contact_phone
        }
        for s in shelters
    ]

    report = {
        "report_id": report_id,
        "title": "DATHEON AI - Comprehensive Flood Hazard & Vulnerability Assessment Report",
        "hackathon": "AI Manthan 2.0 — National Level Hackathon",
        "domain": "AI for Disaster Management",
        "tagline": "Intelligent Risk Analysis. Better Preparedness. Safer Communities.",
        "timestamp": timestamp,
        "location": {
            "name": req.location_name or "Demonstration Catchment Area",
            "latitude": req.latitude,
            "longitude": req.longitude
        },
        "input_indicators": {
            "rainfall_24h_mm": req.rainfall_mm,
            "river_level_relative_m": req.river_level_m,
            "historical_flood_events_10y": req.historical_flood_events,
            "terrain_susceptibility_index": req.terrain_susceptibility,
            "population_vulnerability_index": req.population_vulnerability
        },
        "assessment_outcome": {
            "composite_risk_score": eval_res["risk_score"],
            "risk_category": eval_res["risk_category"],
            "rule_based_score": eval_res["rule_score"],
            "ml_predicted_score": eval_res["ml_predicted_score"],
            "methodology": eval_res["methodology"],
            "data_quality_score": eval_res["data_quality_score"]
        },
        "contributing_factors": eval_res["factors"],
        "recommended_preparedness_actions": eval_res["suggested_actions"],
        "designated_emergency_shelters": shelter_data,
        "data_source_labels": [
            "Central Water Commission (CWC) - Hydro-gauge Baselines (Synthetic)",
            "India Meteorological Department (IMD) - 24hr Rainfall Telemetry (Synthetic)",
            "Sendai Framework for Disaster Risk Reduction (UNDRR)",
            "State Disaster Management Authority (SDMA) Guidelines"
        ],
        "limitations": eval_res["limitations"],
        "legal_and_safety_disclaimer": (
            "HACKATHON PROTOTYPE NOTICE: This report is generated by an academic demonstration system "
            "(DATHEON AI) for the AI Manthan 2.0 hackathon. It does NOT constitute an officially certified "
            "disaster forecast or government evacuation mandate. During real emergencies, always adhere strictly "
            "to announcements from the National Disaster Management Authority (NDMA), District Administration, and NDRF."
        )
    }

    return report
